package cmd

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/spf13/cobra/doc"
)

// Man pages are generated at release time by tools/genman, so no generated
// file is committed — but the tree has to keep rendering them: one page
// per command, flags included. This locks that contract.
func TestManTree(t *testing.T) {
	root := Root()
	root.DisableAutoGenTag = true // the footer names the release, not cobra
	dir := t.TempDir()
	header := &doc.GenManHeader{
		Title:   "PORTS",
		Section: "1",
		Source:  "ports test",
		Manual:  "ports manual",
	}
	if err := doc.GenManTree(root, header, dir); err != nil {
		t.Fatalf("GenManTree: %v", err)
	}

	// one page per command in the tree — a new command without a page
	// fails here, so man pages can't silently fall behind
	names := []string{"ports", "ports-list", "ports-find", "ports-free", "ports-kill", "ports-doctor", "ports-diff", "ports-completion"}
	pages := map[string]string{}
	for _, name := range names {
		page, err := os.ReadFile(filepath.Join(dir, name+".1"))
		if err != nil {
			t.Errorf("missing man page %s.1: %v", name, err)
			continue
		}
		if strings.Contains(string(page), "Auto generated by spf13/cobra") {
			t.Errorf("%s.1 carries the cobra autogen footer", name)
		}
		pages[name] = string(page)
	}

	// the root page documents the full flag set — a flag added to the
	// tree lands here without anyone remembering man pages exist
	for _, flag := range []string{"--sort", "--watch", "--interval", "--tree", "--format"} {
		if !strings.Contains(pages["ports"], flag) {
			t.Errorf("ports.1 does not document %s", flag)
		}
	}

	// subcommand pages point back at the root
	if !strings.Contains(pages["ports-doctor"], `\fBports(1)\fP`) {
		t.Error("ports-doctor.1 has no SEE ALSO pointing at ports(1)")
	}
}
